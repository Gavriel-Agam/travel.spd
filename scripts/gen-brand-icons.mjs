// Writes src/data/brandIcons.ts: the brand logos offered in the category bank
// (Categories › Category & brand bank), as SVG paths from simple-icons (CC0),
// so they ship with the app and show offline. Brands simple-icons doesn't have
// get a monogram badge in the brand's colour instead.
// Usage: node scripts/gen-brand-icons.mjs  (simple-icons is a dev dependency)
import { writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

/** id in the app (stored as "b:<id>", at most 14 characters) → simple-icons slug. */
const FROM_SIMPLE_ICONS = {
  grab: 'grab',
  gojek: 'gojek',
  shopee: 'shopee',
  uber: 'uber',
  lidl: 'lidl',
  carrefour: 'carrefour',
  starbucks: 'starbucks',
  mcdonalds: 'mcdonalds',
  zara: 'zara',
  ikea: 'ikea',
  burgerking: 'burgerking',
  kfc: 'kfc',
  airbnb: 'airbnb',
  booking: 'bookingdotcom',
  hm: 'handm',
  uniqlo: 'uniqlo',
};

/** Not in simple-icons: a short monogram on the brand colour. */
const MONOGRAMS = {
  '7eleven': { title: '7-Eleven', hex: '008163', text: '7' },
  bolt: { title: 'Bolt', hex: '34D186', text: 'B' },
  familymart: { title: 'FamilyMart', hex: '00A040', text: 'FM' },
  lawson: { title: 'Lawson', hex: '0068B7', text: 'L' },
  decathlon: { title: 'Decathlon', hex: '0082C3', text: 'D' },
};

const bySlug = new Map(Object.values(si).filter((i) => i && i.slug).map((i) => [i.slug, i]));
const out = {};
for (const [id, slug] of Object.entries(FROM_SIMPLE_ICONS)) {
  const icon = bySlug.get(slug);
  if (!icon) throw new Error(`simple-icons has no ${slug}`);
  out[id] = { title: icon.title, hex: icon.hex, path: icon.path };
}
for (const [id, m] of Object.entries(MONOGRAMS)) out[id] = m;
for (const id of Object.keys(out)) if (id.length > 14) throw new Error(`${id} is too long`);

const body = `// Generated by scripts/gen-brand-icons.mjs. Do not edit by hand.
// Logos: simple-icons (CC0); each logo is a trademark of its owner.
export type BrandIcon = { title: string; hex: string; path?: string; text?: string };

export const BRAND_ICONS: Record<string, BrandIcon> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync('src/data/brandIcons.ts', body);
console.log(`${Object.keys(out).length} brands written`);
