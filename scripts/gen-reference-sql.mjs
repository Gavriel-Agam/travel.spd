// Generates the reference-data migration from src/data/*.json so the app's
// bundled fallback and the database always hold the same list.
// Usage: node scripts/gen-reference-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const currencies = JSON.parse(readFileSync('src/data/currencies.json', 'utf8'));
const categories = JSON.parse(readFileSync('src/data/categories.json', 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const cur = currencies
  .map((c, i) => `  (${q(c.code)}, ${q(c.name_en)}, ${q(c.name_he)}, ${q(c.symbol)}, ${q(c.flag)}, ${c.minor_units}, ${i + 1})`)
  .join(',\n');
const cat = categories
  .map((c, i) => `  (${q(c.key)}, ${q(c.name)}, ${q(c.icon)}, ${q(c.color)}, ${(i + 1) * 10})`)
  .join(',\n');

const sql = `-- Generated by scripts/gen-reference-sql.mjs. Do not edit by hand.
-- Adding a currency is a data change: append it to src/data/currencies.json and
-- ship a new migration with an insert ... on conflict do update.

insert into public.currencies (code, name_en, name_he, symbol, flag, minor_units, sort_order) values
${cur}
on conflict (code) do update set
  name_en = excluded.name_en, name_he = excluded.name_he, symbol = excluded.symbol,
  flag = excluded.flag, minor_units = excluded.minor_units, sort_order = excluded.sort_order;

insert into public.expense_categories (key, name, icon, color, sort_order) values
${cat}
on conflict (key) where trip_id is null do update set
  name = excluded.name, icon = excluded.icon, color = excluded.color, sort_order = excluded.sort_order;
`;

writeFileSync('supabase/migrations/20261101000002_reference_data.sql', sql);
console.log(`wrote ${currencies.length} currencies, ${categories.length} categories`);
